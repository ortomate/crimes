// One generated capability reference for humans, agents and the landing page.
import { execFileSync } from "node:child_process";
import { cp, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import {
  builtInDetectors,
  builtInAssetDetectors,
  SCHEMA_VERSION,
} from "../packages/core/dist/index.js";

const root = fileURLToPath(new URL("../", import.meta.url));
const version = JSON.parse(
  await readFile(resolve(root, "packages/cli/package.json"), "utf8"),
).version;
const detectors = [...builtInDetectors, ...builtInAssetDetectors].sort((a, b) =>
  a.id.localeCompare(b.id),
);
const help = execFileSync(
  process.execPath,
  [resolve(root, "packages/cli/dist/index.js"), "--help"],
  { encoding: "utf8" },
).trim();
const optional = detectors.filter((d) => d.defaultOff).map((d) => d.id);
const markdown = `# CLI and detector reference

Generated by \`pnpm docs:generate\` from the built CLI and detector registry.
Version **${version}**, JSON schema **${SCHEMA_VERSION}**.
See [agent usage](./agent-usage.md), [configuration](./configuration.md), and [scoring](./scoring.md) for interpretation.

## Commands

\`\`\`text
${help}
\`\`\`

Use \`crimes <command> --help\` for that command's complete options.
\`scan --changed\` selects files; it does not distinguish old findings from new ones.
Use \`diff\`, \`verdict\`, or a baseline when you need a finding delta.

## Detectors

${detectors.length} registered detectors; ${optional.length} optional and off by default.
An optional id in \`detectors.enable\` adds that detector without disabling the defaults.

| ID | Charge | Default |
| --- | --- | --- |
${detectors.map((d) => `| \`${d.id}\` | ${d.name.replaceAll("|", "\\|")} | ${d.defaultOff ? "Off (optional)" : "On"} |`).join("\n")}
`;
const llms = `# crimes

Local, deterministic change-risk and agent-risk CLI. MIT. No LLM or cloud required.
Prepared package version: ${version}. Use npm view crimes version to verify the published version.
JSON schema: ${SCHEMA_VERSION}. TypeScript, JavaScript, Python, cross-language analysis and universal checks.

## Workflow

- Install: npm install -g crimes (Node.js >=18); one-shot: npx crimes scan .
- Agent setup: crimes init --agents; normal use refreshes generated skills or reports the safe update action.
- Before editing: crimes context src/file.ts --root . --format json
- Read analysis_status, coverage.warnings, evidence, related_files and likely_tests. No findings is not proof of safety.
- Scope planning: crimes scan --files src/a.ts,src/b.ts --format json
- After editing: crimes scan --changed --format json
- Committed branch delta: crimes verdict --base origin/main --fail-on new-high
- Legacy pins: crimes migrate-pins --format json; review the plan before --apply.
- Optional detectors: ${optional.join(", ")}.
- Default human scan: five files, strongest finding plus diminishing contributions from distinct claims.
- JSON preserves all visible findings. Interpret fingerprints as opaque, and triage by type + claim + subject.
- test_gap is test-discovery evidence, not measured behavioural coverage.

## Documentation

- https://crimes.sh/docs/agent-usage/
- https://crimes.sh/docs/reference/
- https://crimes.sh/docs/skills/
- https://crimes.sh/docs/api-types/
- https://crimes.sh/docs/json-schema/
- https://crimes.sh/docs/scoring/
- https://crimes.sh/docs/releases/v${version}/
`;
const escapeHtml = (text) =>
  text.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");
// A source-only fixture makes examples independent of clone depth, checkout
// location and local Git history. They still come from the actual built CLI.
const fixtureParent = await mkdtemp(resolve(tmpdir(), "crimes-docs-"));
const fixtureRoot = resolve(fixtureParent, "messy-ts-app");
let fixture;
let human;
try {
  await cp(resolve(root, "examples/messy-ts-app"), fixtureRoot, { recursive: true });
  const scanArgs = [resolve(root, "packages/cli/dist/index.js"), "scan", fixtureRoot];
  const scanOptions = {
    encoding: "utf8",
    env: { ...process.env, CRIMES_NOW: "2026-09-06T00:00:00Z", NO_COLOR: "1" },
  };
  fixture = JSON.parse(
    execFileSync(process.execPath, [...scanArgs, "--format", "json"], scanOptions),
  );
  fixture.repo.root = "/path/to/messy-ts-app";
  human =
    execFileSync(process.execPath, scanArgs, scanOptions)
      .trim()
      .split("\n")
      .slice(0, 22)
      .join("\n") + "\n… (excerpt)";
} finally {
  await rm(fixtureParent, { recursive: true, force: true });
}
const excerpt = {
  schema_version: fixture.schema_version,
  report_type: fixture.report_type,
  findings: fixture.findings.slice(0, 1),
};
let landing = await readFile(resolve(root, "apps/website/landing/index.html"), "utf8");
landing = landing
  .replace(/("softwareVersion"\s*:\s*")[^"]+/, `$1${version}`)
  .replace(/(<span class="pill">v)[0-9.]+/, `$1${version}`)
  .replace(
    /(<span class="pill">[\s\S]*?href="\/docs\/releases\/v)[0-9.]+/,
    `$1${version}`,
  )
  .replace(/(currently\s*<code>")[^"]+/, `$1${SCHEMA_VERSION}`);
for (const [name, content] of [
  ["example-human", human],
  ["example-json", JSON.stringify(excerpt, null, 2)],
]) {
  const expression = new RegExp(
    `<!-- generated:${name} -->[\\s\\S]*?<!-- /generated:${name} -->`,
  );
  if (!expression.test(landing))
    throw new Error(`Missing generated landing block ${name}`);
  landing = landing.replace(
    expression,
    `<!-- generated:${name} -->\n        <pre><code>${escapeHtml(content)}</code></pre>\n        <!-- /generated:${name} -->`,
  );
}
for (const [file, content] of [
  ["docs/reference.md", markdown],
  ["docs/fixtures/messy-ts-app.json", JSON.stringify(fixture, null, 2) + "\n"],
  ["apps/website/landing/llms.txt", llms],
  ["apps/website/landing/index.html", landing],
]) {
  if (process.argv.includes("--check")) {
    if ((await readFile(resolve(root, file), "utf8").catch(() => "")) !== content)
      throw new Error(`${file} is stale; run pnpm docs:generate after pnpm build`);
  } else await writeFile(resolve(root, file), content);
}
